"""Regenerate UI fonts and disjoint fallback CSS from pinned original assets.

Run: uv run scripts/subset-ui-fonts.py
No build or visitor request runs this script. Full families remain the fallback.
"""

import argparse
import hashlib
import json
import string
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
SOURCES = [
    ("sora-ui", "d2909123a6a8ed2f928055f002c32f63ee93496b470c1a344873f955111fca53", "400 700"),
    ("hanken-ui", "1f21c6eaa0000f3329cfcfac966b43d5bebf5aa610303e33294ac31bc6f4bb59", "400 700"),
    ("mono-ui", "615a7673d37b1dd624e2deeb572a1a238f9b32981bf3fc44f87aa14f3bd7d04b", "500"),
]
FAMILIES = {
    "display": ("Sora", "85.29%", "25.5%", "113.73%"),
    "body": ("Hanken Grotesk", "99.07%", "30.02%", "100.94%"),
    "mono": ("JetBrains Mono", "75.79%", "22.29%", "134.59%"),
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def unicode_ranges(codepoints):
    ranges = []
    for value in sorted(codepoints):
        if ranges and value == ranges[-1][1] + 1:
            ranges[-1][1] = value
        else:
            ranges.append([value, value])
    return ",".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}" for start, end in ranges)


def fallback_css(full_fonts, source_dir, manifest):
    assigned = {family: {ord(char) for char in font["characters"]} for family, font in zip(FAMILIES, manifest)}
    css = ["/* Generated by scripts/subset-ui-fonts.py; do not edit by hand. */"]
    for font in full_fonts:
        family = font["family"]
        name = FAMILIES[family][0]
        coverage = set(TTFont(source_dir / font["file"]).getBestCmap()) - assigned[family]
        assigned[family].update(coverage)
        if not coverage:
            continue
        css.append(
            f'@font-face {{ font-family: "{name} Full"; font-style: normal; '
            f'font-weight: {font["weight"]}; font-display: {font["display"]}; '
            f'src: url("./fonts/full/{font["file"]}") format("woff2"); '
            f'unicode-range: {unicode_ranges(coverage)}; }}'
        )
    css.append("/* Match the original next/font/google Arial fallback metrics. */")
    for family, (name, ascent, descent, size) in FAMILIES.items():
        css.append(
            f'@font-face {{ font-family: "{name} Fallback"; src: local("Arial"); '
            f'ascent-override: {ascent}; descent-override: {descent}; '
            f'line-gap-override: 0%; size-adjust: {size}; }}'
        )
        css.append(f'html {{ --font-{family}-full: "{name} Full", "{name} Fallback"; }}')
    (ROOT / "src/theme/fonts-full.css").write_text("\n".join(css) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / "src/theme/fonts/full")
    args = parser.parse_args()
    full_fonts = json.loads((ROOT / "src/theme/full-fonts.json").read_text())
    for font in full_fonts:
        if digest(args.source_dir / font["file"]) != font["sha256"]:
            raise SystemExit("Original font checksum mismatch: " + font["file"])
    sources = {digest(path): path for path in args.source_dir.glob("*.woff2")}
    missing = [checksum for _, checksum, _ in SOURCES if checksum not in sources]
    if missing:
        raise SystemExit("Missing pinned original fonts: " + ", ".join(missing))

    copy = (ROOT / "src/i18n/messages.ts").read_text()
    # Include transformed eyebrows and ASCII in arbitrary movie names/searches.
    characters = sorted({ord(char) for char in string.printable + copy + copy.upper() + copy.lower()})
    destination = ROOT / "src/theme/fonts"
    destination.mkdir(exist_ok=True)
    manifest = []
    for stem, checksum, weight in SOURCES:
        font = TTFont(sources[checksum], recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]  # Preserve original kerning, ligatures and alternates.
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=characters)
        subsetter.subset(font)
        if "fvar" in font:
            font = instantiateVariableFont(font, {"wght": (400, 700)}, inplace=True)
        path = destination / f"{stem}.woff2"
        font.save(path)
        manifest.append({
            "file": path.name,
            "family": font["name"].getDebugName(1),
            "weight": weight,
            "characters": "".join(chr(codepoint) for codepoint in sorted(font.getBestCmap())),
            "bytes": path.stat().st_size,
            "sha256": digest(path),
            "sourceSha256": checksum,
        })
    (ROOT / "src/theme/ui-fonts.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    fallback_css(full_fonts, args.source_dir, manifest)
    print("Generated UI fonts: " + str(sum(font["bytes"] for font in manifest)) + " bytes")


if __name__ == "__main__":
    main()
