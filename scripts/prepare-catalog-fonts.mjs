import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const sourceFonts = new URL('src/theme/fonts/', root);
const destination = new URL('public/catalog-fonts/', root);

await mkdir(destination, { recursive: true });
await cp(sourceFonts, new URL('fonts/', destination), { recursive: true });

const fontFaces = [
  ['display', 'sora-ui.woff2', '400 700', 'optional'],
  ['body', 'hanken-ui.woff2', '400 700', 'swap'],
  ['mono', 'mono-ui.woff2', '500', 'optional'],
];
const uiCss = fontFaces.map(([family, file, weight, display]) =>
  `@font-face{font-family:${family};src:url("/catalog-fonts/fonts/${file}") format("woff2");font-display:${display};font-weight:${weight}}`,
).join('\n');
await writeFile(new URL('ui-fonts.css', destination), `${uiCss}\n`);

const fullCss = await readFile(new URL('src/theme/fonts-full.css', root), 'utf8');
const catalogShellFontCss = `${uiCss}\n${fullCss.replaceAll('./fonts/full/', '/catalog-fonts/fonts/full/')}`;
await writeFile(
  new URL('fonts-full.css', destination),
  catalogShellFontCss,
);
await writeFile(
  new URL('src/theme/catalog-shell-fonts.ts', root),
  `/* Generated by scripts/prepare-catalog-fonts.mjs; do not edit by hand. */\nexport const catalogShellFontCss = ${JSON.stringify(catalogShellFontCss)};\n`,
);

console.log('Catalog font assets prepared.');
